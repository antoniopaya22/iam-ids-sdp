#!/usr/bin/env bash
# Writes .env with random lab secrets (Keycloak admin, demo users, demo TOTP secrets,
# controller client secret). Run once before `docker compose up`. Keeps an existing .env
# unless --force is given. The file is git-ignored: never commit it.
set -euo pipefail
cd "$(dirname "$0")/.."

if [ -f .env ] && [ "${1:-}" != "--force" ]; then
    echo ".env already exists (use --force to regenerate)"
    exit 0
fi

rand() { # length
    LC_ALL=C tr -dc 'A-Za-z0-9' </dev/urandom | head -c "$1"
}

umask 077
{
    echo "# Generated by scripts/gen-env.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ). Lab only; do not commit."
    echo "SDP_MODE=proposed"
    echo "COMPOSE_PROFILES=proposed"
    echo "KC_ADMIN_PASSWORD=$(rand 24)"
    echo "KC_CONTROLLER_SECRET=$(rand 32)"
    for u in ALICE BOB CAROL BENCH; do
        echo "${u}_PASSWORD=$(rand 20)"
        # Demo TOTP secret (raw string, as Keycloak stores it). Lab-only shortcut: the
        # client container computes the code an authenticator app would show.
        echo "${u}_OTP_SECRET=$(rand 20)"
    done
} > .env
echo "wrote .env"
