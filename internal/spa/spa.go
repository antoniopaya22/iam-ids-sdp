// Package spa wraps fwknop, the Single Packet Authorization implementation used by the
// lab (Debian 12 packages fwknop-server / fwknop-client 2.6.10):
//
//   - rendering fwknopd's access.conf from per-session stanzas,
//   - supervising fwknopd and reloading it when the stanzas change,
//   - sending an SPA packet with the fwknop client,
//   - removing the firewall rules fwknopd opened for a client (revocation).
package spa

import (
	"crypto/rand"
	"encoding/base64"
	"errors"
	"fmt"
	"net"
	"regexp"
	"sort"
	"strings"
)

// Stanza is one access.conf entry: a source address allowed to open ports when it
// sends an SPA packet encrypted with Key and authenticated with HMACKey.
type Stanza struct {
	ID            string   // session or device id, written as a comment
	Source        string   // "ANY" or an IPv4 address / CIDR
	OpenPorts     []string // e.g. "tcp/8443"
	KeyBase64     string   // Rijndael key
	HMACKeyBase64 string   // HMAC-SHA256 key
	AccessTimeout int      // seconds the firewall rule stays after a valid SPA packet
}

var (
	idRe   = regexp.MustCompile(`^[A-Za-z0-9._:-]{1,128}$`)
	portRe = regexp.MustCompile(`^(tcp|udp)/([0-9]{1,5})$`)
	b64Re  = regexp.MustCompile(`^[A-Za-z0-9+/]+={0,2}$`)
)

// Validate rejects values that could break (or inject into) access.conf.
func (s Stanza) Validate() error {
	if !idRe.MatchString(s.ID) {
		return fmt.Errorf("stanza: invalid id %q", s.ID)
	}
	if s.Source != "ANY" {
		if ip := net.ParseIP(s.Source); ip == nil || ip.To4() == nil {
			if _, n, err := net.ParseCIDR(s.Source); err != nil || n.IP.To4() == nil {
				return fmt.Errorf("stanza %s: invalid source %q", s.ID, s.Source)
			}
		}
	}
	if len(s.OpenPorts) == 0 {
		return fmt.Errorf("stanza %s: no ports", s.ID)
	}
	for _, p := range s.OpenPorts {
		if !portRe.MatchString(p) {
			return fmt.Errorf("stanza %s: invalid port %q", s.ID, p)
		}
	}
	for name, k := range map[string]string{"key": s.KeyBase64, "hmac key": s.HMACKeyBase64} {
		b, err := base64.StdEncoding.DecodeString(k)
		if err != nil || len(b) < 16 || !b64Re.MatchString(k) {
			return fmt.Errorf("stanza %s: invalid %s", s.ID, name)
		}
	}
	if s.AccessTimeout <= 0 || s.AccessTimeout > 86400 {
		return fmt.Errorf("stanza %s: access timeout out of range", s.ID)
	}
	return nil
}

// RenderAccessConf renders the stanzas in a stable order. fwknopd refuses to start
// without stanzas, so when there are none a placeholder that can never match
// (source 127.0.0.2, random keys) is written instead.
func RenderAccessConf(stanzas []Stanza) (string, error) {
	sorted := append([]Stanza(nil), stanzas...)
	sort.Slice(sorted, func(i, j int) bool { return sorted[i].ID < sorted[j].ID })
	if len(sorted) == 0 {
		k, h := NewKeys()
		sorted = []Stanza{{ID: "placeholder", Source: "127.0.0.2", OpenPorts: []string{"tcp/1"},
			KeyBase64: k, HMACKeyBase64: h, AccessTimeout: 1}}
	}
	var b strings.Builder
	b.WriteString("# Generated by the SDP agent. Do not edit: rewritten on every session change.\n")
	for _, s := range sorted {
		if err := s.Validate(); err != nil {
			return "", err
		}
		fmt.Fprintf(&b, "\n# %s\n", s.ID)
		fmt.Fprintf(&b, "SOURCE                  %s\n", s.Source)
		fmt.Fprintf(&b, "OPEN_PORTS              %s\n", strings.Join(s.OpenPorts, ","))
		fmt.Fprintf(&b, "KEY_BASE64              %s\n", s.KeyBase64)
		fmt.Fprintf(&b, "HMAC_KEY_BASE64         %s\n", s.HMACKeyBase64)
		b.WriteString("HMAC_DIGEST_TYPE        SHA256\n")
		b.WriteString("REQUIRE_SOURCE_ADDRESS  Y\n")
		fmt.Fprintf(&b, "FW_ACCESS_TIMEOUT       %d\n", s.AccessTimeout)
	}
	return b.String(), nil
}

// NewKeys returns a fresh random Rijndael key (32 bytes) and HMAC key (64 bytes).
func NewKeys() (key, hmacKey string) {
	k := make([]byte, 32)
	h := make([]byte, 64)
	if _, err := rand.Read(k); err != nil {
		panic(err)
	}
	if _, err := rand.Read(h); err != nil {
		panic(err)
	}
	return base64.StdEncoding.EncodeToString(k), base64.StdEncoding.EncodeToString(h)
}

// KeyFile is the format of the per-device static SPA keys issued by the lab PKI
// (used to knock on the controller before the mTLS connection).
type KeyFile struct {
	KeyBase64     string
	HMACKeyBase64 string
}

// ParseKeyFile parses "KEY_BASE64 <k>\nHMAC_KEY_BASE64 <h>\n".
func ParseKeyFile(b []byte) (KeyFile, error) {
	var kf KeyFile
	for _, line := range strings.Split(string(b), "\n") {
		f := strings.Fields(line)
		if len(f) != 2 {
			continue
		}
		switch f[0] {
		case "KEY_BASE64":
			kf.KeyBase64 = f[1]
		case "HMAC_KEY_BASE64":
			kf.HMACKeyBase64 = f[1]
		}
	}
	if kf.KeyBase64 == "" || kf.HMACKeyBase64 == "" {
		return kf, errors.New("spa key file: KEY_BASE64 and HMAC_KEY_BASE64 are required")
	}
	return kf, nil
}
