// DaemonConfig describes how to run fwknopd.
type DaemonConfig struct {
	Binary        string // default "fwknopd"
	Dir           string // writable directory for configs, run dirs and the digest cache
	Interface     string // interface fwknopd sniffs SPA packets on
	SPAPort       int    // UDP port (default 62201)
	PcapLoopSleep int    // microseconds between pcap polls (default 10000)
	Logger        *log.Logger
}

// Daemon supervises fwknopd and keeps its access.conf in sync with a set of stanzas.
//
// fwknopd 2.6.10 re-reads access.conf on SIGHUP, but the restart takes about one
// second and SPA packets that arrive meanwhile are lost. The daemon therefore reloads
// "blue/green": it starts a second fwknopd with the new stanzas, waits until its event
// loop runs (~70 ms), then stops the old instance. Both instances share the digest
// cache (replay protection) and leave the firewall chains in place on exit, so rules
// opened earlier stay until they expire or are removed by RemoveRulesFor.
//
// Concurrent changes are coalesced: every caller waits until a reload that includes
// its change has completed, and one reload can serve many callers.
type Daemon struct {
	cfg DaemonConfig

	mu       sync.Mutex
	cond     *sync.Cond
	stanzas  map[string]Stanza
	version  uint64 // bumped on every change
	applied  uint64 // version running in fwknopd
	lastErr  error
	running  *exec.Cmd
	slot     int
	stopping bool
}

// NewDaemon returns a daemon; call Start to launch fwknopd.
func NewDaemon(cfg DaemonConfig) *Daemon {
	if cfg.Binary == "" {
		cfg.Binary = "fwknopd"
	}
	if cfg.SPAPort == 0 {
		cfg.SPAPort = 62201
	}
	if cfg.PcapLoopSleep == 0 {
		cfg.PcapLoopSleep = 10000
	}
	if cfg.Logger == nil {
		cfg.Logger = log.New(os.Stderr, "[fwknopd] ", log.LstdFlags)
	}
	d := &Daemon{cfg: cfg, stanzas: map[string]Stanza{}}
	d.cond = sync.NewCond(&d.mu)
	return d
}

// RenderServerConf renders fwknopd.conf for one instance (slot) of the daemon.
func RenderServerConf(cfg DaemonConfig, slot int) string {
	run := filepath.Join(cfg.Dir, fmt.Sprintf("run%d", slot))
	return strings.Join([]string{
		"# Generated by the SDP agent.",
		fmt.Sprintf("PCAP_INTF                   %s;", cfg.Interface),
		fmt.Sprintf("PCAP_FILTER                 udp port %d;", cfg.SPAPort),
		fmt.Sprintf("PCAP_LOOP_SLEEP             %d;", cfg.PcapLoopSleep),
		"ENABLE_PCAP_PROMISC         N;",
		"MAX_SPA_PACKET_AGE          120;",
		"ENABLE_SPA_PACKET_AGING     Y;",
		"ENABLE_DIGEST_PERSISTENCE   Y;",
		fmt.Sprintf("DIGEST_FILE                 %s;", filepath.Join(cfg.Dir, "digest.cache")),
		fmt.Sprintf("FWKNOP_RUN_DIR              %s;", run),
		fmt.Sprintf("FWKNOP_PID_FILE             %s;", filepath.Join(run, "fwknopd.pid")),
		fmt.Sprintf("ACCESS_FILE                 %s;", filepath.Join(cfg.Dir, "access.conf")),
		// Only INPUT access: the AH terminates the connection itself (reverse proxy).
		"ENABLE_IPT_FORWARDING       N;",
		"ENABLE_IPT_LOCAL_NAT        N;",
		"ENABLE_IPT_SNAT             N;",
		"ENABLE_IPT_OUTPUT           N;",
		// Keep the chains across the blue/green swap (see Daemon).
		"FLUSH_IPT_AT_INIT           N;",
		"FLUSH_IPT_AT_EXIT           N;",
		"IPT_INPUT_ACCESS            ACCEPT, filter, INPUT, 1, FWKNOP_INPUT, 1;",
		"",
	}, "\n")
}

// Start writes the initial configuration and launches fwknopd.
func (d *Daemon) Start(ctx context.Context) error {
	if d.cfg.Interface == "" {
		return errors.New("spa: no capture interface")
	}
	if err := os.MkdirAll(d.cfg.Dir, 0o700); err != nil {
		return err
	}
	d.mu.Lock()
	defer d.mu.Unlock()
	if err := d.reloadLocked(ctx); err != nil {
		return err
	}
	go d.loop()
	return nil
}

// Set adds or replaces stanzas and returns once fwknopd runs with them.
func (d *Daemon) Set(ctx context.Context, stanzas ...Stanza) error {
	for _, s := range stanzas {
		if err := s.Validate(); err != nil {
			return err
		}
	}
	d.mu.Lock()
	for _, s := range stanzas {
		d.stanzas[s.ID] = s
	}
	return d.waitApplied(ctx)
}

// Remove deletes stanzas by id and returns once fwknopd no longer accepts them.
func (d *Daemon) Remove(ctx context.Context, ids ...string) error {
	d.mu.Lock()
	changed := false
	for _, id := range ids {
		if _, ok := d.stanzas[id]; ok {
			delete(d.stanzas, id)
			changed = true
		}
	}
	if !changed {
		d.mu.Unlock()
		return nil
	}
	return d.waitApplied(ctx)
}

// waitApplied must be called with d.mu held; it releases it.
func (d *Daemon) waitApplied(ctx context.Context) error {
	d.version++
	want := d.version
	d.cond.Broadcast()
	stop := context.AfterFunc(ctx, func() {
		d.mu.Lock()
		d.cond.Broadcast()
		d.mu.Unlock()
	})
	defer stop()
	for d.applied < want && ctx.Err() == nil && !d.stopping {
		d.cond.Wait()
	}
	err := d.lastErr
	if ctx.Err() != nil {
		err = ctx.Err()
	}
	d.mu.Unlock()
	return err
}

// loop applies pending changes; one reload covers every change made before it started.
func (d *Daemon) loop() {
	d.mu.Lock()
	defer d.mu.Unlock()
	for !d.stopping {
		for d.applied >= d.version && !d.stopping {
			d.cond.Wait()
		}
		if d.stopping {
			return
		}
		ctx, cancel := context.WithTimeout(context.Background(), 10*time.Second)
		err := d.reloadLocked(ctx)
		cancel()
		if err != nil {
			d.cfg.Logger.Printf("reload failed: %v", err)
		}
		d.cond.Broadcast()
	}
}

// reloadLocked renders the current stanzas and swaps fwknopd instances. Called with
// d.mu held; the lock is released while waiting for the new instance.
func (d *Daemon) reloadLocked(ctx context.Context) error {
	target := d.version
	list := make([]Stanza, 0, len(d.stanzas))
	for _, s := range d.stanzas {
		list = append(list, s)
	}
	conf, err := RenderAccessConf(list)
	if err != nil {
		d.lastErr = err
		d.applied = target
		return err
	}
	if err := writeFileAtomic(filepath.Join(d.cfg.Dir, "access.conf"), []byte(conf)); err != nil {
		d.lastErr = err
		return err
	}
	d.slot = 1 - d.slot
	slot := d.slot
	old := d.running
	confPath := filepath.Join(d.cfg.Dir, fmt.Sprintf("fwknopd%d.conf", slot))
	if err := writeFileAtomic(confPath, []byte(RenderServerConf(d.cfg, slot))); err != nil {
		d.lastErr = err
		return err
	}
	run := filepath.Join(d.cfg.Dir, fmt.Sprintf("run%d", slot))
	_ = os.MkdirAll(run, 0o700)
	_ = os.Remove(filepath.Join(run, "fwknopd.pid"))

	d.mu.Unlock()
	cmd, err := d.spawn(ctx, confPath, filepath.Join(d.cfg.Dir, "access.conf"))
	if err == nil && old != nil {
		_ = old.Process.Signal(syscall.SIGTERM)
		go func() { _ = old.Wait() }()
	}
	d.mu.Lock()

	if err != nil {
		d.lastErr = err
		return err
	}
	d.running = cmd
	d.applied = target
	d.lastErr = nil
	return nil
}

// spawn starts fwknopd and waits until it reports its event loop is running.
func (d *Daemon) spawn(ctx context.Context, conf, access string) (*exec.Cmd, error) {
	cmd := exec.Command(d.cfg.Binary, "-f", "-c", conf, "-a", access) //nolint:gosec // fixed binary, generated paths
	pr, pw := io.Pipe()
	cmd.Stdout, cmd.Stderr = pw, pw
	if err := cmd.Start(); err != nil {
		return nil, fmt.Errorf("start fwknopd: %w", err)
	}
	ready := make(chan struct{})
	exited := make(chan error, 1)
	go func() {
		sc := bufio.NewScanner(pr)
		once := sync.Once{}
		for sc.Scan() {
			line := sc.Text()
			d.cfg.Logger.Printf("pid %d: %s", cmd.Process.Pid, line)
			if strings.Contains(line, "main event loop") {
				once.Do(func() { close(ready) })
			}
		}
	}()
	go func() { exited <- cmd.Wait(); _ = pw.Close() }()
	select {
	case <-ready:
		// Re-attach the exit watcher for the instance's lifetime.
		go func() {
			err := <-exited
			d.mu.Lock()
			current := d.running == cmd
			stopping := d.stopping
			d.mu.Unlock()
			if current && !stopping {
				d.cfg.Logger.Fatalf("fwknopd exited unexpectedly: %v", err)
			}
		}()
		return cmd, nil
	case err := <-exited:
		return nil, fmt.Errorf("fwknopd exited during start-up: %v", err)
	case <-ctx.Done():
		_ = cmd.Process.Kill()
		return nil, fmt.Errorf("fwknopd start-up: %w", ctx.Err())
	}
}

// Stop terminates fwknopd.
func (d *Daemon) Stop() {
	d.mu.Lock()
	d.stopping = true
	cmd := d.running
	d.cond.Broadcast()
	d.mu.Unlock()
	if cmd != nil {
		_ = cmd.Process.Signal(syscall.SIGTERM)
	}
}

// Stanzas returns a copy of the current stanzas.
func (d *Daemon) Stanzas() []Stanza {
	d.mu.Lock()
	defer d.mu.Unlock()
	out := make([]Stanza, 0, len(d.stanzas))
	for _, s := range d.stanzas {
		out = append(out, s)
	}
	return out
}

func writeFileAtomic(path string, b []byte) error {
	tmp := path + ".tmp"
	if err := os.WriteFile(tmp, b, 0o600); err != nil {
		return err
	}
	return os.Rename(tmp, path)
}
